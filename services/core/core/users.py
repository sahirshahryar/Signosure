# How long the tokens generated by generate_verification_token() should be
VERIFICATION_TOKEN_LEN = 32

# How many iterations to use with PKBDF2.
PASSWORD_HASHING_ITERATIONS = 1_000_000


def generate_verification_token() -> str:
    """
    Generates a token that can be used to verify a user's email address, either
    during account creation or when resetting a password.
    """
    random_bytes = secrets.token_bytes(VERIFICATION_TOKEN_LEN)
    return base64.urlsafe_b64encode(random_bytes).decode("utf-8").rstrip("=")


def hash_password(
    plaintext: str, salt: bytes, iterations: int = PASSWORD_HASHING_ITERATIONS
) -> bytes:
    """
    Hashes a password using the PBKDF2 algorithm and the specified number of
    iterations
    """
    return hashlib.pbkdf2_hmac("sha256", plaintext.encode(), salt, iterations)


def verify_password(plaintext: str, stored_hash: str) -> bool:
    """
    Verifies a password against a stored hash.

    The stored hash format is: pbkdf2:sha256:{iterations}:{salt_b64}:{hash_b64}
    """
    try:
        parts = stored_hash.split(":")
        if len(parts) != 5 or parts[0] != "pbkdf2" or parts[1] != "sha256":
            return False

        iterations = int(parts[2])
        salt = base64.b64decode(parts[3])
        expected_hash = base64.b64decode(parts[4])

        computed_hash = hash_password(plaintext, salt, iterations)
        return secrets.compare_digest(computed_hash, expected_hash)
    except (ValueError, IndexError):
        return False


async def validate_registration_code(code: str) -> bool:
    """
    Validates a registration code for either annotation or collection.
    """
    code = code.strip().upper()
    if not re.fullmatch(r"^([AC][A-Z0-9]{6}[A-Z])$", code):
        return False

    # Registration code starts with A: annotation
    if code.startswith("A"):
        dataset = await Dataset.find_one(
            Dataset.annotator_reg_open == True,  # noqa: E712
            Dataset.annotator_code == code,
        )
    else:
        # Registration code starts with C: collection
        dataset = await Dataset.find_one(
            Dataset.collector_reg_open == True,  # noqa: E712
            Dataset.collector_code == code,
        )

    return dataset is not None


@router.post(path="/validate")
async def validate_user(
    email: str = Form(...),
    password: str = Form(...),
    registration_code: Optional[str] = Form(None),
    *,
    skip_registration_check: bool = False,
):
    """
    Validates the contents of the user account creation form with the following
    checks:
    1. Ensure the user's email address is
       a. valid
       b. unique
    2. Ensure the submitted password has the following qualities:
       a. At least get_config('users.min_password_len') characters (default 12).
          If a value less than 8 is stored in the config, enforce a minimum of 8
       b. Not the same as their email address
    3. If get_config('users.allow_open_registration') is false, ensure that the
       user provided a registration code, and that there exists a Dataset which
       has that registration code and has registration_open == True.
    """
    logger.trace("core.users: Entered validate_user()")
    errors = list()

    try:
        # Check 1a: Email validity
        parsed_email = validate_email(email)
        norm_email = parsed_email.email

        # Check 1b: Email uniqueness (case-insensitive)
        # MongoDB regex for case-insensitive exact match
        existing_user = await User.find_one(
            {"email": {"$regex": f"^{re.escape(norm_email)}$", "$options": "i"}}
        )
        if existing_user:
            errors.append("users.reg.email.in-use")
    except EmailNotValidError:
        errors.append("users.reg.email.invalid-format")

    # Check 2a: Password length
    min_password_len = int(get_config_value("users.min-password-len", int))

    if min_password_len < 8:
        min_password_len = 8

    if len(password) < min_password_len:
        errors.append(f"users.reg.password.too-short|{min_password_len}")

    # Check 2b: Password not same as email (case-insensitive)
    if password.lower() == email.lower():
        errors.append("users.reg.password.same-as-email")

    if skip_registration_check:
        return {"valid": True}

    # Check 3: Registration code validation
    allow_open_registration = get_config_value(
        "users.allow-open-registration", bool
    )

    if not allow_open_registration:
        if not registration_code:
            errors.append("users.reg.code.missing")
        elif not await validate_registration_code(registration_code):
            errors.append("users.reg.code.invalid")

    if errors:
        logger.trace(f"Rejected user creation: {errors}")
        raise HTTPException(
            status_code=400, detail={"valid": False, "errors": errors}
        )

    return {"valid": True}


@router.post(path="/create")
async def create_user(
    email: str = Form(...),
    password: str = Form(...),
    registration_code: Optional[str] = Form(None),
):
    """
    Creates a user with the following steps:
    1. Validate the user via `validate_user()`
    2. Generate the user's password hash
    3. Initialize the user with default permissions
    4. Store the user in the database
    5. Initialize scoped permissions for the user
    6. Send a confirmation email to the user
    """

    # Validate the user
    try:
        await validate_user(email, password, registration_code)
    except HTTPException as e:
        return e.detail

    # Normalize the email address
    parsed_email = validate_email(email)
    norm_email = parsed_email.email

    # Hash user's password
    salt = os.urandom(32)
    password_hash = hash_password(password, salt, PASSWORD_HASHING_ITERATIONS)

    salt_encoded = base64.b64encode(salt).decode("utf-8")
    hash_encoded = base64.b64encode(password_hash).decode("utf-8")
    pass_hash_str = (
        f"pbkdf2:sha256:{PASSWORD_HASHING_ITERATIONS}:"
        f"{salt_encoded}:{hash_encoded}"
    )

    # Generate email confirmation token and expiration
    confirm_token = generate_verification_token()
    confirmation_time = get_config_value("users.email-confirmation-time", int)
    confirm_exp = int(time.time() * 1000) + confirmation_time

    # Initialize scoped permissions if registration code provided
    scoped_permissions = {}
    admin_scopes = set()

    # TODO: Create default permission mask for open registration
    permission_mask = 0

    if registration_code is not None:
        is_annotator = registration_code.startswith("A")

        # Find the dataset with this registration code
        if is_annotator:
            dataset = await Dataset.find_one(
                Dataset.annotator_reg_open == True,  # noqa: E712
                Dataset.annotator_code == registration_code.strip().upper(),
            )
        else:
            dataset = await Dataset.find_one(
                Dataset.collector_reg_open == True,  # noqa: E712
                Dataset.collector_code == registration_code.strip().upper(),
            )

        if dataset:
            scope = await PermissionScope.get(dataset.scope_id)

            if scope:
                # Get default permissions for collectors or annotators
                if is_annotator:
                    permission_mask = scope.default_unscoped_annotation
                    permissions = scope.default_annotation
                else:
                    permission_mask = scope.default_unscoped_collection
                    permissions = scope.default_collection

                # Store scoped permissions
                scoped_permissions[str(scope.id)] = permissions

    # Create and store the user
    new_user = User(
        email=norm_email,
        confirm_token=confirm_token,
        confirm_exp=confirm_exp,
        validated=False,
        oauth=False,
        pass_hash=pass_hash_str,
        admin=False,
        unscoped_permissions=permission_mask,
        scoped_permissions=scoped_permissions,
        admin_scopes=admin_scopes,
        activity_id="",  # Will be set after creating UserActivity
    )

    await new_user.save()

    # Create UserActivity document for this user
    user_activity = UserActivity(
        user_id=str(new_user.id),
        collection_activity={},
        annotation_activity={},
    )
    await user_activity.save()

    # Update user with activity_id
    new_user.activity_id = str(user_activity.id)
    await new_user.save()

    # TODO: Send a confirmation email to the user
    # This should call a function like: send_confirmation_email(norm_email, confirm_token)
    # The email should contain a link with the confirmation token for the user to verify their account

    return {
        "success": True,
        "user_id": str(new_user.id),
        "message": "users.reg.success",
    }


@router.post(path="/login")
async def login_user(
    response: Response,
    email: str = Form(...),
    password: str = Form(...),
):
    """
    Authenticates a user and creates a session.

    Returns:
        On success: { "success": True, "user_id": str }
        On failure: HTTPException with 401 status
    """
    # Find user by email (case-insensitive)
    user = await User.find_one(
        {"email": {"$regex": f"^{re.escape(email)}$", "$options": "i"}}
    )

    # Use constant-time comparison to prevent timing attacks
    if user is None:
        # Hash a dummy password to prevent timing attacks
        hash_password(
            password, b"dummy_salt_value", PASSWORD_HASHING_ITERATIONS
        )
        raise HTTPException(status_code=401, detail="users.login.invalid")

    # Verify password
    if not verify_password(password, user.pass_hash):
        raise HTTPException(status_code=401, detail="users.login.invalid")

    # Check if user has LOGIN permission
    if not user.has_permissions(UnscopedPermission.LOGIN):
        raise HTTPException(status_code=403, detail="users.login.disabled")

    # Create session and set cookie
    create_session(str(user.id), response)

    return {
        "success": True,
        "user_id": str(user.id),
        "validated": user.validated,
    }


@router.get(path="/me")
async def get_current_user_info(
    session_id: Optional[str] = Cookie(None, alias="session_id"),
):
    """
    Returns information about the currently logged-in user.

    Returns:
        User info if authenticated, or 401 if not logged in
    """
    from core.auth import get_session

    if not session_id:
        raise HTTPException(status_code=401, detail="users.me.not-logged-in")

    session_data = get_session(session_id)
    if not session_data:
        raise HTTPException(status_code=401, detail="users.me.invalid-session")

    user_id = session_data.get("user_id")
    if not user_id:
        raise HTTPException(status_code=401, detail="users.me.invalid-session")

    user = await User.get(user_id)
    if not user:
        raise HTTPException(status_code=401, detail="users.me.user-not-found")

    return {
        "id": str(user.id),
        "email": user.email,
        "name": user.name,
        "validated": user.validated,
        "admin": user.admin,
        "unscoped_permissions": UnscopedPermission.decode(
            UnscopedPermission(user.unscoped_permissions)
        ),
        "visibility_permissions": ScopedPermission.decode(
            user.permissions_in_any_scope() & ScopedPermission.WEB_VISIBILITY
        ),
    }


@router.post(path="/logout")
async def logout_user(
    response: Response,
    session_id: Optional[str] = Cookie(None, alias="session_id"),
):
    """
    Logs out the current user by deleting their session.

    Returns:
        { "success": True } on success
        { "success": False } if no session existed
    """
    if not session_id:
        return {"success": False, "message": "users.logout.no-session"}

    deleted = delete_session(session_id)

    # Clear the session cookie
    response.delete_cookie(
        key="session_id", path="/", httponly=True, secure=True
    )

    return {"success": deleted}


